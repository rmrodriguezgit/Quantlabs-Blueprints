// Validator: no false errors on distributed examples; detects and repairs injected faults.
import { readFileSync } from "node:fs";
import assert from "node:assert/strict";
import { build } from "esbuild";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
const out = join(mkdtempSync(join(tmpdir(), "ql-validation-")), "validation.mjs");
await build({ entryPoints: [new URL("../src/renderer/validation.ts", import.meta.url).pathname], bundle: true, format: "esm", platform: "node", outfile: out, logLevel: "error" });
const { validateGraph, repairGraph } = await import(out);
const library = JSON.parse(readFileSync(new URL("../public/blueprints/library.json", import.meta.url)));
for (const entry of library.entries) {
  const errors = validateGraph(entry.graph).filter((i) => i.severity === "error");
  assert.deepEqual(errors.map((e) => e.message), [], `${entry.id} has false validation errors`);
}
const base = structuredClone(library.entries.find((e) => e.id === "laya-yfinance").graph);
const broken = structuredClone(base);
broken.edges = broken.edges.filter((e) => e.target !== "Pesos");
broken.nodes.find((n) => n.id === "Laya").data.params.max_rows = 99999;
broken.nodes.find((n) => n.id === "Feedback").data.params.positions = "sideways";
const found = validateGraph(broken).filter((i) => i.severity === "error");
assert.ok(found.some((i) => i.node === "Pesos" && i.message.includes("falta la entrada")));
assert.ok(found.some((i) => i.node === "Laya" && i.message.includes("fuera del rango")));
assert.ok(found.some((i) => i.node === "Feedback" && i.message.includes("opción válida")));
const repaired = repairGraph(broken);
assert.equal(repaired.remaining.filter((i) => i.severity === "error").length, 0, JSON.stringify(repaired.remaining));
assert.equal(repaired.graph.nodes.find((n) => n.id === "Laya").data.params.max_rows, 3000);
assert.ok(repaired.graph.edges.some((e) => e.target === "Pesos" && e.source === "Laya"));
const cyclic = structuredClone(base);
cyclic.edges.push({ id: "loop", source: "Feedback", target: "Indicadores", sourceHandle: "frame", targetHandle: "frame" });
assert.ok(validateGraph(cyclic).some((i) => i.message.includes("ciclo") || i.message.includes("ya tiene otra conexión")));
const fx = structuredClone(library.entries.find((e) => e.id === "area-returns").graph);
const src = fx.nodes.find((n) => n.data.kind === "source");
src.data.params = { ...src.data.params, source: "yfinance", ticker: "EURUSD=X" };
assert.ok(validateGraph(fx).some((i) => i.message.includes("VWAP") && i.fix));
const rl = structuredClone(library.entries.find((e) => e.id === "research-rl-agent").graph);
const agent = rl.nodes.find((n) => n.data.kind === "rl_agent");
rl.edges = rl.edges.filter((e) => e.target !== agent.id);
const rlFixed = repairGraph(rl).graph;
const feeder = rlFixed.edges.find((e) => e.target === agent.id && e.targetHandle === "frame");
assert.equal(rl.nodes.find((n) => n.id === feeder.source).data.kind, "features", "repair must feed indicator columns, not raw OHLCV");
const raw = structuredClone(library.entries.find((e) => e.id === "research-rl-agent").graph);
const rawAgent = raw.nodes.find((n) => n.data.kind === "rl_agent");
const rawSource = raw.nodes.find((n) => n.data.kind === "source");
raw.edges = raw.edges.map((e) => (e.target === rawAgent.id && e.targetHandle === "frame" ? { ...e, source: rawSource.id } : e));
const columnIssue = validateGraph(raw).find((i) => i.node === rawAgent.id && i.message.includes("columnas"));
assert.equal(columnIssue?.severity, "error", "engine-fatal missing columns must block execution");
assert.equal(columnIssue.fix?.type, "reconnect");
const reconnected = repairGraph(raw);
assert.equal(raw.nodes.find((n) => n.id === reconnected.graph.edges.find((e) => e.target === rawAgent.id && e.targetHandle === "frame").source).data.kind, "features");
console.log(`Validation checks passed: ${library.entries.length} examples clean, faults detected and repaired, cycle and FX/VWAP rules, column-aware reconnection.`);
